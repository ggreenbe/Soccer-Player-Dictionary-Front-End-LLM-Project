def add_player():
  while True:
    try:
      player_add = input("Which player do you want to add to the menu?\n").title() #.title capitalizes the first letter of every word. I use this because it's a player's name
      legends_or_stars = input(f"Do you want to add {player_add} to legends or stars?\n").lower() #.lower keeps the response lowercase to correspond with the dictionary sections
      pos_choice = input(f"Do you want to add {player_add} to midfielders or forwards?\n").lower()
      add_player_stat = input("You now need to add a stat to this player. What stat do you want to add?\n").lower()
      add_player_stat_num = int(input(f"What is the number for {player_add}'s {add_player_stat}?\n"))
      players[legends_or_stars][pos_choice][player_add] = {
          add_player_stat : add_player_stat_num
      }
      break
    except:
      print("There was an error in your response. Try again.")

